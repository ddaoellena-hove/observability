const ScenarioMapCard = ({ scenario }: { scenario: ScenarioMapItem }) => {
  const [paramsOpen, setParamsOpen] = useState(false);

  return (
    <div className="msp-card">
      {/* Header */}
      <div className="msp-card__header">
        <span className="msp-card__title">{scenario.title}</span>
        <NavigationDropdown
          label="···"
          align="right"
          className="msp-card__more-dropdown"
          items={[
            { id: "edit",      label: "Modifier" },
            { id: "duplicate", label: "Dupliquer" },
            { id: "delete",    label: "Supprimer", dividerAbove: true },
          ]}
        />
      </div>

      {/* Points d'intérêt */}
      <div className="msp-section">
        <InfoCard label="Points d'intérêt" icon={<IconPoi />}>
          {scenario.pois.map((poi, i) => (
            <div key={i} className="msp-poi">
              <PoiIcon type={poi.icon} />
              <div className="msp-poi__info">
                <span className="msp-poi__name">{poi.name}</span>
                {poi.address && <span className="msp-poi__address">{poi.address}</span>}
                {poi.modes.length > 0 && (
                  <div className="msp-poi__modes">
                    {poi.modes.map((m) => (
                      <TransportBadge key={m} mode={m} />
                    ))}
                  </div>
                )}
              </div>
            </div>
          ))}
        </InfoCard>
      </div>

      {/* Paramètres associés */}
      <button
        className="msp-params-toggle"
        type="button"
        onClick={() => setParamsOpen((v) => !v)}
      >
        <div className="msp-params-toggle__left">
          <IconParameter />
          Paramètre(s) associé(s)
        </div>
        <svg
          className={`msp-params-toggle__chevron ${paramsOpen ? "is-open" : ""}`}
          width="14" height="14" viewBox="0 0 14 14" fill="none"
        >
          <path d="M3 5l4 4 4-4" stroke="#9ca3af" strokeWidth="1.4" strokeLinecap="round" strokeLinejoin="round"/>
        </svg>
      </button>

      {paramsOpen && scenario.params && scenario.params.length > 0 && (
        <div className="msp-params-content">
          {scenario.params.map((p, i) => (
            <div key={i} className="msp-param-item">{p}</div>
          ))}
        </div>
      )}
    </div>
  );
};

